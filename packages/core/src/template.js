// Templates are generated from real environment files: keys kept, values
// stripped. They are never maintained by hand, so they can't drift.

// keys: [{ name, required, description, example }]
export const buildTemplateText = (keys, { project, service } = {}) => {
  const lines = [];
  if (project) {
    lines.push(`# Template for ${project}${service ? ` (${service})` : ""}`);
    lines.push("# Generated by StoreEnv. Fill in the values, then rename to .env");
    lines.push("");
  }
  for (const key of keys) {
    const notes = [];
    if (key.description) notes.push(key.description);
    if (key.required) notes.push("required");
    if (notes.length) lines.push(`# ${notes.join(" | ")}`);
    lines.push(`${key.name}=${key.example && !/[\s#"']/.test(key.example) ? key.example : ""}`);
  }
  return `${lines.join("\n")}\n`;
};

// Compares a committed .env.example with the generated template.
export const compareWithTemplate = (templateKeys, fileKeys) => {
  const template = new Set(templateKeys);
  const file = new Set(fileKeys);
  return {
    missingInFile: [...template].filter((key) => !file.has(key)).sort(),
    extraInFile: [...file].filter((key) => !template.has(key)).sort(),
  };
};
